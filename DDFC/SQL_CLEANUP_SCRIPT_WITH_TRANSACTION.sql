-- ????????????????????????????????????????????????????????????????????????????????
-- DDFC Database Cleanup Script with Transaction Support
-- Purpose: Remove all lookup and transactional data with rollback capability
-- Usage: Run against DDFC database (SQL Server)
-- Note: Modify 'YourDatabaseName' to your actual database name
-- ????????????????????????????????????????????????????????????????????????????????

-- Use your database
USE [YourDatabaseName];
GO

-- ????????????????????????????????????????????????????????????????????????????????
-- BEGIN TRANSACTION FOR SAFE CLEANUP
-- ????????????????????????????????????????????????????????????????????????????????
BEGIN TRANSACTION CleanupTransaction;
BEGIN TRY

    PRINT '????????????????????????????????????????????????????????????????????????????????';
    PRINT 'Starting Database Cleanup Transaction';
    PRINT '????????????????????????????????????????????????????????????????????????????????';
    PRINT '';

    -- ?? Disable all foreign key constraints temporarily ??????????????????????????
    PRINT '[1/8] Disabling all foreign key constraints...';
    EXEC sp_MSForEachTable @command1='ALTER TABLE ? NOCHECK CONSTRAINT ALL';
    PRINT '? Foreign key constraints disabled';
    PRINT '';

    -- ?? Clear Workflow Engine Data ????????????????????????????????????????????????
    PRINT '[2/8] Clearing Workflow Engine data...';
    DELETE FROM [workflow].[RequestActions];
    DELETE FROM [workflow].[RequestSteps];
    DELETE FROM [workflow].[Requests];
    DELETE FROM [workflow].[StepTransitions];
    DELETE FROM [workflow].[StepActions];
    DELETE FROM [workflow].[ProcessSteps];
    DELETE FROM [workflow].[Processes];
    PRINT '? Workflow data cleared (RequestActions, RequestSteps, Requests, StepTransitions, StepActions, ProcessSteps, Processes)';
    PRINT '';

    -- ?? Clear DDFC Audit & History Tables ?????????????????????????????????????????
    PRINT '[3/8] Clearing audit and history tables...';
    DELETE FROM [ddfc].[RequestWorkflowHistories];
    PRINT '? RequestWorkflowHistories cleared';
    PRINT '';

    -- ?? Clear Payment Data ?????????????????????????????????????????????????????????
    PRINT '[4/8] Clearing payment data...';
    DELETE FROM [ddfc].[PaymentChallans];
    DELETE FROM [ddfc].[Payments];
    PRINT '? Payments and PaymentChallans cleared';
    PRINT '';

    -- ?? Clear Task & Availability Data ???????????????????????????????????????????
    PRINT '[5/8] Clearing task and availability data...';
    DELETE FROM [ddfc].[TaskAssignments];
    DELETE FROM [ddfc].[EmployeeAvailabilities];
    DELETE FROM [ddfc].[Appointments];
    PRINT '? TaskAssignments, EmployeeAvailabilities, and Appointments cleared';
    PRINT '';

    -- ?? Clear Support & Communication Data ?????????????????????????????????????
    PRINT '[6/8] Clearing support tickets and notifications...';
    DELETE FROM [ddfc].[TicketReplies];
    DELETE FROM [ddfc].[SupportTickets];
    DELETE FROM [ddfc].[CustomerNotifications];
    PRINT '? SupportTickets, TicketReplies, and CustomerNotifications cleared';
    PRINT '';

    -- ?? Clear Technical & Engineering Data ????????????????????????????????????
    PRINT '[7/8] Clearing technical and engineering documents...';
    DELETE FROM [ddfc].[CadAssignments];
    DELETE FROM [ddfc].[CadFiles];
    DELETE FROM [ddfc].[PlotMergings];
    DELETE FROM [ddfc].[PlotAnnexations];
    DELETE FROM [ddfc].[ArchitectUndertakings];
    DELETE FROM [ddfc].[DelayUndertakings];
    DELETE FROM [ddfc].[PossessionCertificates];
    DELETE FROM [ddfc].[SoilTestReports];
    DELETE FROM [ddfc].[SurveyObservations];
    DELETE FROM [ddfc].[SurveyForms];
    DELETE FROM [ddfc].[MEPReports];
    DELETE FROM [ddfc].[StructuralReports];
    DELETE FROM [ddfc].[Documents];
    DELETE FROM [ddfc].[PlanRevisionRequests];
    DELETE FROM [ddfc].[ArchitecturalPlans];
    PRINT '? CAD files, Technical reports, Surveys, and Plans cleared';
    PRINT '';

    -- ?? Clear Main Business Data ??????????????????????????????????????????????
    PRINT '[8/8] Clearing main business entities and master data...';
    
    -- Clear possession requests (main entity)
    DELETE FROM [ddfc].[PossessionRequests];
    PRINT '  ? PossessionRequests cleared';
    
    -- Clear customers
    DELETE FROM [ddfc].[Customers];
    PRINT '  ? Customers cleared';
    
    -- Clear plots
    DELETE FROM [ddfc].[Plots];
    PRINT '  ? Plots cleared';
    
    -- Clear packages
    DELETE FROM [ddfc].[PackageLineItems];
    DELETE FROM [ddfc].[Packages];
    PRINT '  ? Packages and PackageLineItems cleared';
    
    -- Clear templates
    DELETE FROM [ddfc].[Templates];
    PRINT '  ? Templates cleared';
    
    -- Clear departments (must be after all references)
    DELETE FROM [ddfc].[Departments];
    PRINT '  ? Departments cleared';
    PRINT '';

    -- ?? Clear Identity Data ????????????????????????????????????????????????????
    PRINT '[Identity] Clearing users and roles...';
    DELETE FROM [identity].[UserClaims];
    DELETE FROM [identity].[UserLogins];
    DELETE FROM [identity].[UserTokens];
    DELETE FROM [identity].[UserRoles];
    DELETE FROM [identity].[Users];
    DELETE FROM [identity].[RoleClaims];
    DELETE FROM [identity].[Roles];
    PRINT '? All identity data (Users, Roles, Claims, Logins, Tokens) cleared';
    PRINT '';

    -- ?? Re-enable all foreign key constraints ??????????????????????????????????
    PRINT '[Constraints] Re-enabling all foreign key constraints...';
    EXEC sp_MSForEachTable @command1='ALTER TABLE ? CHECK CONSTRAINT ALL';
    PRINT '? Foreign key constraints re-enabled';
    PRINT '';

    -- ?? Reset Identity Seeds ???????????????????????????????????????????????????
    PRINT '[Seeds] Resetting identity column seeds...';
    DBCC CHECKIDENT ('[identity].[UserClaims]', RESEED, 0);
    DBCC CHECKIDENT ('[identity].[RoleClaims]', RESEED, 0);
    PRINT '? Identity seeds reset to 0';
    PRINT '';

    -- ?? Commit Transaction ????????????????????????????????????????????????????
    COMMIT TRANSACTION CleanupTransaction;

    PRINT '????????????????????????????????????????????????????????????????????????????????';
    PRINT '? CLEANUP COMPLETED SUCCESSFULLY!';
    PRINT '????????????????????????????????????????????????????????????????????????????????';
    PRINT '';

END TRY
BEGIN CATCH
    -- If any error occurs, rollback all changes
    ROLLBACK TRANSACTION CleanupTransaction;

    PRINT '';
    PRINT '????????????????????????????????????????????????????????????????????????????????';
    PRINT '? ERROR OCCURRED - TRANSACTION ROLLED BACK';
    PRINT '????????????????????????????????????????????????????????????????????????????????';
    PRINT '';
    PRINT 'Error Number: ' + CAST(ERROR_NUMBER() AS VARCHAR(10));
    PRINT 'Error Severity: ' + CAST(ERROR_SEVERITY() AS VARCHAR(10));
    PRINT 'Error State: ' + CAST(ERROR_STATE() AS VARCHAR(10));
    PRINT 'Error Message: ' + ERROR_MESSAGE();
    PRINT '';
    PRINT 'All changes have been rolled back. Database remains unchanged.';
    PRINT '';

END CATCH;

GO

