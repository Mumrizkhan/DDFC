-- ????????????????????????????????????????????????????????????????????????????????
-- DDFC Database Cleanup Script
-- Purpose: Remove all lookup data and transactional records from DDFC and Workflow databases
-- Usage: Run this script against your DDFC database
-- ????????????????????????????????????????????????????????????????????????????????

-- ?? Enable Advanced Options ??????????????????????????????????????????????????????
USE master;
GO

-- ?? Switch to DDFC Database ??????????????????????????????????????????????????????
USE [YourDatabaseName];
GO

-- ????????????????????????????????????????????????????????????????????????????????
-- PART 1: DISABLE ALL FOREIGN KEY CONSTRAINTS
-- ????????????????????????????????????????????????????????????????????????????????
PRINT '==== DISABLING FOREIGN KEY CONSTRAINTS ====';
GO

EXEC sp_MSForEachTable @command1='ALTER TABLE ? NOCHECK CONSTRAINT ALL';
GO

-- ????????????????????????????????????????????????????????????????????????????????
-- PART 2: DELETE WORKFLOW ENGINE DATA (workflow schema)
-- ????????????????????????????????????????????????????????????????????????????????
PRINT '==== CLEARING WORKFLOW ENGINE DATA ====';
GO

-- Delete in dependency order
DELETE FROM [workflow].[RequestActions];
DELETE FROM [workflow].[RequestSteps];
DELETE FROM [workflow].[Requests];
DELETE FROM [workflow].[StepTransitions];
DELETE FROM [workflow].[StepActions];
DELETE FROM [workflow].[ProcessSteps];
DELETE FROM [workflow].[Processes];

PRINT '? Workflow data cleared';
GO

-- ????????????????????????????????????????????????????????????????????????????????
-- PART 3: DELETE DDFC TRANSACTIONAL DATA (ddfc schema)
-- Delete in reverse dependency order (bottom-up from foreign keys)
-- ????????????????????????????????????????????????????????????????????????????????
PRINT '==== CLEARING DDFC TRANSACTIONAL DATA ====';
GO

-- Workflow history and audit trails
DELETE FROM [ddfc].[RequestWorkflowHistories];
PRINT '? RequestWorkflowHistories';

-- Payment related
DELETE FROM [ddfc].[PaymentChallans];
DELETE FROM [ddfc].[Payments];
PRINT '? Payments & PaymentChallans';

-- Task assignments
DELETE FROM [ddfc].[TaskAssignments];
PRINT '? TaskAssignments';

-- Employee management
DELETE FROM [ddfc].[EmployeeAvailabilities];
PRINT '? EmployeeAvailabilities';

-- Appointments
DELETE FROM [ddfc].[Appointments];
PRINT '? Appointments';

-- Support tickets
DELETE FROM [ddfc].[TicketReplies];
DELETE FROM [ddfc].[SupportTickets];
PRINT '? SupportTickets & TicketReplies';

-- Customer notifications
DELETE FROM [ddfc].[CustomerNotifications];
PRINT '? CustomerNotifications';

-- CAD and engineering
DELETE FROM [ddfc].[CadAssignments];
DELETE FROM [ddfc].[CadFiles];
PRINT '? CAD files & assignments';

-- Plot modifications
DELETE FROM [ddfc].[PlotMergings];
DELETE FROM [ddfc].[PlotAnnexations];
PRINT '? Plot modifications';

-- Undertakings
DELETE FROM [ddfc].[ArchitectUndertakings];
DELETE FROM [ddfc].[DelayUndertakings];
PRINT '? Undertakings';

-- Possession certificates and surveys
DELETE FROM [ddfc].[PossessionCertificates];
DELETE FROM [ddfc].[SoilTestReports];
DELETE FROM [ddfc].[SurveyObservations];
DELETE FROM [ddfc].[SurveyForms];
PRINT '? Certificates & Survey data';

-- Technical reports
DELETE FROM [ddfc].[MEPReports];
DELETE FROM [ddfc].[StructuralReports];
PRINT '? Technical reports';

-- Documents and file management
DELETE FROM [ddfc].[Documents];
PRINT '? Documents';

-- Architectural plans
DELETE FROM [ddfc].[PlanRevisionRequests];
DELETE FROM [ddfc].[ArchitecturalPlans];
PRINT '? Architectural plans';

-- Possession requests (main entity - delete last among business entities)
DELETE FROM [ddfc].[PossessionRequests];
PRINT '? PossessionRequests';

-- ????????????????????????????????????????????????????????????????????????????????
-- PART 4: DELETE DDFC MASTER DATA (ddfc schema)
-- ????????????????????????????????????????????????????????????????????????????????
PRINT '==== CLEARING DDFC MASTER DATA ====';
GO

-- Customer data
DELETE FROM [ddfc].[Customers];
PRINT '? Customers';

-- Plots
DELETE FROM [ddfc].[Plots];
PRINT '? Plots';

-- Packages and pricing
DELETE FROM [ddfc].[PackageLineItems];
DELETE FROM [ddfc].[Packages];
PRINT '? Packages & Line Items';

-- Templates
DELETE FROM [ddfc].[Templates];
PRINT '? Templates';

-- Departments
DELETE FROM [ddfc].[Departments];
PRINT '? Departments';

-- ????????????????????????????????????????????????????????????????????????????????
-- PART 5: DELETE IDENTITY DATA (identity schema)
-- ????????????????????????????????????????????????????????????????????????????????
PRINT '==== CLEARING IDENTITY DATA ====';
GO

-- Clear all user-related claims and associations
DELETE FROM [identity].[UserClaims];
DELETE FROM [identity].[UserLogins];
DELETE FROM [identity].[UserTokens];
DELETE FROM [identity].[UserRoles];
PRINT '? User claims, logins, tokens, roles';

-- Clear users
DELETE FROM [identity].[Users];
PRINT '? Users';

-- Clear role claims
DELETE FROM [identity].[RoleClaims];
PRINT '? Role claims';

-- Clear roles
DELETE FROM [identity].[Roles];
PRINT '? Roles';

-- ????????????????????????????????????????????????????????????????????????????????
-- PART 6: RE-ENABLE ALL FOREIGN KEY CONSTRAINTS
-- ????????????????????????????????????????????????????????????????????????????????
PRINT '==== RE-ENABLING FOREIGN KEY CONSTRAINTS ====';
GO

EXEC sp_MSForEachTable @command1='ALTER TABLE ? CHECK CONSTRAINT ALL';
GO

-- ????????????????????????????????????????????????????????????????????????????????
-- PART 7: RESET IDENTITY SEEDS (optional - for clean auto-increment IDs)
-- ????????????????????????????????????????????????????????????????????????????????
PRINT '==== RESETTING IDENTITY SEEDS ====';
GO

-- Reset Identity column seeds for identity schema tables
DBCC CHECKIDENT ('[identity].[UserClaims]', RESEED, 0);
DBCC CHECKIDENT ('[identity].[RoleClaims]', RESEED, 0);
PRINT '? Identity seeds reset';

-- ????????????????????????????????????????????????????????????????????????????????
-- PART 8: VERIFICATION QUERIES
-- ????????????????????????????????????????????????????????????????????????????????
PRINT '==== VERIFICATION QUERIES ====';
GO

PRINT '';
PRINT 'Record counts after cleanup:';
PRINT '???????????????????????????';

SELECT 'Customers' AS [Table Name], COUNT(*) AS [Count] FROM [ddfc].[Customers]
UNION ALL
SELECT 'Plots', COUNT(*) FROM [ddfc].[Plots]
UNION ALL
SELECT 'Packages', COUNT(*) FROM [ddfc].[Packages]
UNION ALL
SELECT 'PackageLineItems', COUNT(*) FROM [ddfc].[PackageLineItems]
UNION ALL
SELECT 'Departments', COUNT(*) FROM [ddfc].[Departments]
UNION ALL
SELECT 'Users', COUNT(*) FROM [identity].[Users]
UNION ALL
SELECT 'Roles', COUNT(*) FROM [identity].[Roles]
UNION ALL
SELECT 'PossessionRequests', COUNT(*) FROM [ddfc].[PossessionRequests]
UNION ALL
SELECT 'Payments', COUNT(*) FROM [ddfc].[Payments]
UNION ALL
SELECT 'TaskAssignments', COUNT(*) FROM [ddfc].[TaskAssignments]
UNION ALL
SELECT 'Appointments', COUNT(*) FROM [ddfc].[Appointments]
UNION ALL
SELECT 'SupportTickets', COUNT(*) FROM [ddfc].[SupportTickets]
UNION ALL
SELECT 'WorkflowProcesses', COUNT(*) FROM [workflow].[Processes]
UNION ALL
SELECT 'WorkflowRequests', COUNT(*) FROM [workflow].[Requests]
ORDER BY [Table Name];

GO

PRINT '';
PRINT '????????????????????????????????????????????????????????????????????????????????';
PRINT '? DATABASE CLEANUP COMPLETED SUCCESSFULLY!';
PRINT '????????????????????????????????????????????????????????????????????????????????';
PRINT '';
PRINT 'All lookup data and transactional records have been removed.';
PRINT 'The database is now ready for fresh seeding.';
PRINT '';
